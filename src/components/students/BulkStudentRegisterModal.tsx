interface BulkStudentInputRow {
  id: string;
  fullName: string;
  collegeRollNumber: string;
  departmentOrCourse: string;
  email: string;
  phone: string;
  password: string;
}

interface CreatedCredentialRow {
  rowNumber: number;
  studentId: string;
  fullName: string;
  collegeRollNumber: string;
  studentIdCode: string;
  departmentOrCourse: string;
  email: string;
  loginId: string;
  password: string;
  passwordAutoGenerated: boolean;
  phone: string;
  cardNumber: string | null;
}

interface FailedStudentRow {
  rowNumber: number;
  fullName: string;
  collegeRollNumber: string;
  email: string;
  reason: string;
}

interface BulkStudentRegisterModalProps {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  organizationName: string;
  courses: Array<{ id: string; name: string; code: string }>;
  semesters: Array<{ id: string; courseId: string; name: string }>;
  academicSessions: Array<{ id: string; name: string }>;
  existingRolls: Set<string>;
  existingEmails: Set<string>;
  onCompleted: () => void;
}

function makeEmptyRow(): BulkStudentInputRow {
  return {
    id: `${Date.now()}-${Math.random().toString(36).slice(2, 7)}`,
    fullName: '',
    collegeRollNumber: '',
    departmentOrCourse: '',
    email: '',
    phone: '',
    password: '',
  };
}

function mapCsvRecordToRow(rec: Record<string, string>): BulkStudentInputRow {
  const norm = new Map<string, string>();
  for (const [k, v] of Object.entries(rec)) {
    const cleanKey = k.trim().toLowerCase().replace(/[^a-z0-9]/g, '');
    norm.set(cleanKey, (v || '').trim());
  }
  const pick = (...aliases: string[]) => {
    for (const a of aliases) {
      const val = norm.get(a);
      if (val) return val;
    }
    return '';
  };
  return {
    id: `${Date.now()}-${Math.random().toString(36).slice(2, 7)}`,
    fullName: pick('fullname', 'name', 'studentname'),
    collegeRollNumber: pick('rollno', 'rollnumber', 'collegerollnumber', 'studentid', 'id', 'roll'),
    departmentOrCourse: pick('departmentcourse', 'department', 'course', 'branch', 'program', 'stream'),
    email: pick('email', 'emailaddress', 'loginemail'),
    phone: pick('phone', 'mobile', 'phonenumber', 'contact'),
    password: pick('password', 'pass', 'initialpassword'),
  };
}

export function BulkStudentRegisterModal({
  open,
  onOpenChange,
  organizationName,
  courses,
  semesters,
  academicSessions,
  existingRolls,
  existingEmails,
  onCompleted,
}: BulkStudentRegisterModalProps) {
  const fileInputRef = useRef<HTMLInputElement>(null);
  const [inputMode, setInputMode] = useState<'table' | 'csv' | 'paste'>('table');
  const [rows, setRows] = useState<BulkStudentInputRow[]>([makeEmptyRow(), makeEmptyRow(), makeEmptyRow()]);
  const [pasteText, setPasteText] = useState('');
  const [defaultCourseId, setDefaultCourseId] = useState('');
  const [defaultSemesterId, setDefaultSemesterId] = useState('');
  const [defaultAcademicSessionId, setDefaultAcademicSessionId] = useState('');
  const [autoGenerateId, setAutoGenerateId] = useState(true);
  const [submitting, setSubmitting] = useState(false);

  const [result, setResult] = useState<{
    created: CreatedCredentialRow[];
    failed: FailedStudentRow[];
    summary: { total: number; createdCount: number; failedCount: number };
  } | null>(null);

  const filteredSemesters = useMemo(
    () => semesters.filter((s) => !defaultCourseId || s.courseId === defaultCourseId),
    [semesters, defaultCourseId]
  );

  // Live client-side validation warnings per row
  const rowWarnings = useMemo(() => {
    const seenRolls = new Set<string>();
    const seenEmails = new Set<string>();
    const warnings = new Map<string, string>();
    for (const r of rows) {
      const hasAny = r.fullName.trim() || r.collegeRollNumber.trim() || r.email.trim();
      if (!hasAny) continue;
      const roll = r.collegeRollNumber.trim().toLowerCase();
      const email = r.email.trim().toLowerCase();
      if (!r.fullName.trim()) {
        warnings.set(r.id, 'Name required');
      } else if (!roll) {
        warnings.set(r.id, 'Roll No / Student ID required');
      } else if (existingRolls.has(roll)) {
        warnings.set(r.id, `Duplicate Roll No "${r.collegeRollNumber}" (already registered)`);
      } else if (seenRolls.has(roll)) {
        warnings.set(r.id, `Duplicate Roll No "${r.collegeRollNumber}" in this batch`);
      } else if (email && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
        warnings.set(r.id, 'Invalid email format');
      } else if (email && (existingEmails.has(email) || seenEmails.has(email))) {
        warnings.set(r.id, `Duplicate email "${r.email}"`);
      }
      if (roll) seenRolls.add(roll);
      if (email) seenEmails.add(email);
    }
    return warnings;
  }, [rows, existingRolls, existingEmails]);

  const nonEmptyRows = useMemo(
    () => rows.filter((r) => r.fullName.trim() || r.collegeRollNumber.trim() || r.email.trim()),
    [rows]
  );

  const handleDownloadSampleCsv = () => {
    exportToCsv('qivora-bulk-students-template.csv', [
      {
        Name: 'Aarav Sharma',
        RollNo: 'BCA-2026-101',
        DepartmentCourse: 'BCA',
        Email: 'aarav.sharma@college.edu',
        Phone: '9876543210',
        Password: '',
      },
      {
        Name: 'Zoya Khan',
        RollNo: 'BCA-2026-102',
        DepartmentCourse: 'BCA',
        Email: '',
        Phone: '9876543211',
        Password: '',
      },
    ]);
    toast.success('Sample CSV template downloaded.');
  };

  const handleCsvUpload = (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;
    Papa.parse<Record<string, string>>(file, {
      header: true,
      skipEmptyLines: true,
      complete: (parsed) => {
        const mapped = parsed.data
          .map(mapCsvRecordToRow)
          .filter((r) => r.fullName || r.collegeRollNumber || r.email);
        if (!mapped.length) {
          toast.error('No valid student rows found in CSV. Check column headers.');
          return;
        }
        setRows(mapped);
        setInputMode('table');
        toast.success(`Loaded ${mapped.length} student row(s) from ${file.name}. Review and submit.`);
      },
      error: () => toast.error('Failed to parse CSV file.'),
    });
    if (fileInputRef.current) fileInputRef.current.value = '';
  };

  const handleParsePasted = () => {
    const trimmed = pasteText.trim();
    if (!trimmed) {
      toast.error('Paste rows first (comma or tab separated).');
      return;
    }
    const lines = trimmed.split(/\r?\n/).filter((l) => l.trim().length > 0);
    // Detect if first line is header
    const firstCols = lines[0].split(/\t|,/).map((c) => c.trim().toLowerCase());
    const looksLikeHeader = firstCols.some((c) => ['name', 'full name', 'roll', 'roll no', 'student id', 'email'].includes(c));

    let parsedRows: BulkStudentInputRow[] = [];
    if (looksLikeHeader) {
      const p = Papa.parse<Record<string, string>>(trimmed, { header: true, skipEmptyLines: true });
      parsedRows = p.data.map(mapCsvRecordToRow).filter((r) => r.fullName || r.collegeRollNumber);
    } else {
      parsedRows = lines.map((line) => {
        const delimiter = line.includes('\t') ? '\t' : ',';
        const cols = line.split(delimiter).map((c) => c.trim());
        return {
          id: `${Date.now()}-${Math.random().toString(36).slice(2, 7)}`,
          fullName: cols[0] || '',
          collegeRollNumber: cols[1] || '',
          departmentOrCourse: cols[2] || '',
          email: cols[3] || '',
          phone: cols[4] || '',
          password: cols[5] || '',
        };
      });
    }

    if (!parsedRows.length) {
      toast.error('Could not parse any student rows.');
      return;
    }
    setRows(parsedRows);
    setPasteText('');
    setInputMode('table');
    toast.success(`Parsed ${parsedRows.length} student row(s) into the table.`);
  };

  const updateRow = (id: string, field: keyof Omit<BulkStudentInputRow, 'id'>, value: string) => {
    setRows((prev) => prev.map((r) => (r.id === id ? { ...r, [field]: value } : r)));
  };

  const removeRow = (id: string) => {
    setRows((prev) => (prev.length <= 1 ? [makeEmptyRow()] : prev.filter((r) => r.id !== id)));
  };

  const handleSubmitBulk = async () => {
    if (!nonEmptyRows.length) {
      toast.error('Enter or upload at least one student row first.');
      return;
    }
    setSubmitting(true);
    try {
      const res = await apiRequest<{
        created: CreatedCredentialRow[];
        failed: FailedStudentRow[];
        summary: { total: number; createdCount: number; failedCount: number };
      }>('/org/students/bulk', {
        method: 'POST',
        body: {
          students: nonEmptyRows.map((r) => ({
            fullName: r.fullName.trim(),
            collegeRollNumber: r.collegeRollNumber.trim(),
            departmentOrCourse: r.departmentOrCourse.trim() || null,
            email: r.email.trim() || null,
            phone: r.phone.trim() || null,
            password: r.password.trim() || null,
          })),
          defaultCourseId: defaultCourseId || null,
          defaultSemesterId: defaultSemesterId || null,
          defaultAcademicSessionId: defaultAcademicSessionId || null,
          autoGenerateId,
        },
      });

      setResult(res);
      if (res.summary.createdCount > 0) {
        toast.success(
          `Created ${res.summary.createdCount} student account(s)${res.summary.failedCount ? ` (${res.summary.failedCount} skipped)` : ''}.`
        );
        onCompleted();
      } else {
        toast.error('No student accounts were created. Review the validation reasons below.');
      }
    } catch (err: unknown) {
      toast.error(err instanceof Error ? err.message : 'Bulk registration failed.');
    } finally {
      setSubmitting(false);
    }
  };

  const handleCopyAllCredentials = async () => {
    if (!result?.created.length) return;
    const header = `${organizationName} — QIVORA Student Portal Credentials\n` + '='.repeat(60);
    const body = result.created
      .map(
        (c, idx) =>
          `${idx + 1}. ${c.fullName} (Roll: ${c.collegeRollNumber} | Course: ${c.departmentOrCourse})\n   Login ID: ${c.loginId}\n   Password: ${c.password}${c.cardNumber ? `\n   Digital ID: ${c.cardNumber}` : ''}`
      )
      .join('\n\n');
    try {
      await navigator.clipboard.writeText(`${header}\n\n${body}`);
      toast.success(`Copied credentials for ${result.created.length} student(s) to clipboard.`);
    } catch {
      toast.error('Clipboard permission unavailable — use Download CSV instead.');
    }
  };

  const handleDownloadCredentialsCsv = () => {
    if (!result?.created.length) return;
    exportToCsv(
      `qivora-student-credentials-${new Date().toISOString().slice(0, 10)}.csv`,
      result.created.map((c) => ({
        Name: c.fullName,
        RollNo: c.collegeRollNumber,
        StudentID: c.studentIdCode,
        DepartmentCourse: c.departmentOrCourse,
        LoginID_Email: c.loginId,
        Password: c.password,
        Phone: c.phone,
        DigitalIDCard: c.cardNumber || '',
      }))
    );
    toast.success('Credentials CSV downloaded.');
  };

  const handlePrintCredentials = () => {
    if (!result?.created.length) return;
    const iframe = document.createElement('iframe');
    iframe.style.position = 'fixed';
    iframe.style.right = '0';
    iframe.style.bottom = '0';
    iframe.style.width = '0';
    iframe.style.height = '0';
    iframe.style.border = '0';
    document.body.appendChild(iframe);

    const escapeHtml = (s: string) =>
      s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

    const rowsHtml = result.created
      .map(
        (c, i) => `
          <tr>
            <td>${i + 1}</td>
            <td><strong>${escapeHtml(c.fullName)}</strong><br/><span class="muted">${escapeHtml(c.departmentOrCourse)}</span></td>
            <td class="mono">${escapeHtml(c.collegeRollNumber)}</td>
            <td class="mono">${escapeHtml(c.loginId)}</td>
            <td class="mono pwd">${escapeHtml(c.password)}</td>
            <td class="mono">${escapeHtml(c.cardNumber || '—')}</td>
          </tr>
        `
      )
      .join('');

    const html = `<!doctype html>
<html>
<head>
  <title>QIVORA Student Credentials — ${escapeHtml(organizationName)}</title>
  <style>
    body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; color: #0f172a; margin: 24px; }
    h1 { font-size: 18px; margin: 0 0 4px; }
    .sub { font-size: 12px; color: #475569; margin-bottom: 16px; }
    table { width: 100%; border-collapse: collapse; font-size: 12px; }
    th, td { border: 1px solid #cbd5e1; padding: 8px 10px; text-align: left; }
    th { background: #f1f5f9; font-weight: 600; }
    .mono { font-family: ui-monospace, SFMono-Regular, Menlo, monospace; }
    .pwd { font-weight: 700; background: #f8fafc; }
    .muted { color: #64748b; font-size: 11px; }
    .footer { margin-top: 20px; font-size: 10px; color: #64748b; border-top: 1px solid #e2e8f0; padding-top: 8px; }
  </style>
</head>
<body>
  <h1>${escapeHtml(organizationName)} — Student Login Credentials</h1>
  <div class="sub">Generated via QIVORA Smart Library Management System · ${new Date().toLocaleString()} · ${result.created.length} Student(s)</div>
  <table>
    <thead>
      <tr>
        <th>#</th>
        <th>Student & Course</th>
        <th>Roll No</th>
        <th>Login ID (Email)</th>
        <th>Password</th>
        <th>Digital ID</th>
      </tr>
    </thead>
    <tbody>${rowsHtml}</tbody>
  </table>
  <div class="footer">Confidential — Distribute credentials individually to students. Designed &amp; Developed by MOHAMMAD SHARIQ · BCA 1st Year | 2026–2027 Batch.</div>
</body>
</html>`;

    const doc = iframe.contentWindow?.document;
    if (doc) {
      doc.open();
      doc.write(html);
      doc.close();
      iframe.contentWindow?.focus();
      setTimeout(() => {
        iframe.contentWindow?.print();
        setTimeout(() => document.body.removeChild(iframe), 1000);
      }, 250);
    }
  };

  const resetAll = () => {
    setResult(null);
    setRows([makeEmptyRow(), makeEmptyRow(), makeEmptyRow()]);
    setPasteText('');
    setInputMode('table');
  };

  return (
    <Modal
      open={open}
      onOpenChange={(o) => {
        if (!o) setResult(null);
        onOpenChange(o);
      }}
      title={result ? 'Bulk Registration Credentials Summary' : 'Bulk Register Students'}
      description={
        result
          ? 'Save, copy, download, or print these student login credentials now. Passwords are stored securely hashed.'
          : 'Upload a CSV, paste from Excel/Sheets, or enter multiple students directly. Blank passwords auto-generate strong credentials.'
      }
      maxWidth="max-w-5xl"
    >
      {result ? (
        <div className="space-y-5">
          {/* Summary Stats */}
          <div className="grid grid-cols-3 gap-3">
            <div className="rounded-xl border border-slate-200 dark:border-slate-800 p-3.5 bg-slate-50/70 dark:bg-slate-900/50">
              <div className="text-[11px] font-medium text-slate-500">Processed Rows</div>
              <div className="text-xl font-display font-bold mt-0.5 tabular-nums">{result.summary.total}</div>
            </div>
            <div className="rounded-xl border border-emerald-200 dark:border-emerald-900/60 p-3.5 bg-emerald-50/60 dark:bg-emerald-950/30">
              <div className="text-[11px] font-medium text-emerald-700 dark:text-emerald-300">Accounts Created</div>
              <div className="text-xl font-display font-bold text-emerald-700 dark:text-emerald-300 mt-0.5 tabular-nums">
                {result.summary.createdCount}
              </div>
            </div>
            <div className="rounded-xl border border-amber-200 dark:border-amber-900/60 p-3.5 bg-amber-50/60 dark:bg-amber-950/30">
              <div className="text-[11px] font-medium text-amber-700 dark:text-amber-300">Skipped / Duplicates</div>
              <div className="text-xl font-display font-bold text-amber-700 dark:text-amber-300 mt-0.5 tabular-nums">
                {result.summary.failedCount}
              </div>
            </div>
          </div>

          {/* Credentials Distribution Toolbar */}
          {result.created.length > 0 && (
            <div className="flex flex-wrap items-center justify-between gap-3 rounded-xl border border-[#2563EB]/25 bg-[#EFF6FF] dark:bg-[#1E3A8A]/20 px-4 py-3">
              <div className="flex items-center gap-2 text-xs text-[#1E40AF] dark:text-blue-200 font-medium">
                <KeyRound className="h-4 w-4 shrink-0" />
                Ready to distribute login credentials for {result.created.length} student(s)
              </div>
              <div className="flex flex-wrap items-center gap-2">
                <Button size="sm" variant="outline" onClick={handleCopyAllCredentials}>
                  <Copy className="h-3.5 w-3.5" />
                  Copy All
                </Button>
                <Button size="sm" variant="outline" onClick={handleDownloadCredentialsCsv}>
                  <Download className="h-3.5 w-3.5" />
                  Download CSV
                </Button>
                <Button size="sm" onClick={handlePrintCredentials}>
                  <Printer className="h-3.5 w-3.5" />
                  Print Credentials
                </Button>
              </div>
            </div>
          )}

          {/* Created Students Credentials Table */}
          {result.created.length > 0 && (
            <div className="overflow-x-auto rounded-xl border border-slate-200 dark:border-slate-800 max-h-80">
              <table className="w-full text-left text-xs">
                <thead className="sticky top-0 border-b border-slate-200 bg-slate-50 font-semibold text-slate-600 dark:border-slate-800 dark:bg-slate-900 dark:text-slate-300">
                  <tr>
                    <th className="px-3 py-2.5">Student Name</th>
                    <th className="px-3 py-2.5">Roll No / ID</th>
                    <th className="px-3 py-2.5">Dept / Course</th>
                    <th className="px-3 py-2.5">Login ID (Email)</th>
                    <th className="px-3 py-2.5">Password</th>
                    <th className="px-3 py-2.5 text-right">Copy</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-100 dark:divide-slate-800">
                  {result.created.map((c) => (
                    <tr key={c.studentId}>
                      <td className="px-3 py-2 font-medium text-slate-900 dark:text-white">
                        {c.fullName}
                        {c.cardNumber && (
                          <div className="text-[10px] font-mono text-emerald-600 dark:text-emerald-400">
                            ID: {c.cardNumber}
                          </div>
                        )}
                      </td>
                      <td className="px-3 py-2 font-mono">{c.collegeRollNumber}</td>
                      <td className="px-3 py-2 text-slate-600 dark:text-slate-300">{c.departmentOrCourse}</td>
                      <td className="px-3 py-2 font-mono text-[#2563EB] dark:text-[#60A5FA]">{c.loginId}</td>
                      <td className="px-3 py-2">
                        <span className="inline-flex items-center gap-1 rounded bg-slate-100 dark:bg-slate-800 px-2 py-0.5 font-mono font-semibold text-slate-900 dark:text-white">
                          {c.password}
                        </span>
                        {c.passwordAutoGenerated && (
                          <span className="ml-1.5 text-[10px] text-slate-400">auto</span>
                        )}
                      </td>
                      <td className="px-3 py-2 text-right">
                        <Button
                          size="sm"
                          variant="ghost"
                          onClick={async () => {
                            await navigator.clipboard.writeText(
                              `${c.fullName} | Login: ${c.loginId} | Password: ${c.password}`
                            );
                            toast.success(`Copied credentials for ${c.fullName}`);
                          }}
                        >
                          <Copy className="h-3.5 w-3.5" />
                        </Button>
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}

          {/* Failed / Duplicate Validation Errors */}
          {result.failed.length > 0 && (
            <div className="rounded-xl border border-amber-200 dark:border-amber-900/60 bg-amber-50/50 dark:bg-amber-950/20 p-4 space-y-2">
              <div className="flex items-center gap-2 text-xs font-semibold text-amber-800 dark:text-amber-300">
                <AlertTriangle className="h-4 w-4" />
                Skipped Rows ({result.failed.length}) — Duplicates or Validation Issues
              </div>
              <div className="max-h-40 overflow-y-auto divide-y divide-amber-200/60 dark:divide-amber-900/40 text-xs">
                {result.failed.map((f) => (
                  <div key={`${f.rowNumber}-${f.collegeRollNumber}`} className="py-1.5 flex items-start justify-between gap-3">
                    <div>
                      <span className="font-mono text-amber-700 dark:text-amber-400">Row #{f.rowNumber}</span>{' '}
                      <span className="font-medium text-slate-900 dark:text-white">
                        {f.fullName || 'Unnamed'} ({f.collegeRollNumber || 'No Roll'})
                      </span>
                    </div>
                    <span className="text-red-600 dark:text-red-400 text-right">{f.reason}</span>
                  </div>
                ))}
              </div>
            </div>
          )}

          <div className="flex items-center justify-between pt-2 border-t border-slate-200 dark:border-slate-800">
            <Button variant="outline" onClick={resetAll}>
              Register Another Batch
            </Button>
            <Button onClick={() => onOpenChange(false)}>
              <CheckCircle2 className="h-4 w-4" />
              Done
            </Button>
          </div>
        </div>
      ) : (
        <div className="space-y-4">
          {/* Input Mode Switcher */}
          <div className="flex flex-wrap items-center justify-between gap-3">
            <div className="inline-flex rounded-lg bg-slate-100 p-1 dark:bg-slate-800">
              {(
                [
                  ['table', 'Editable Table', Users],
                  ['csv', 'Upload CSV', FileSpreadsheet],
                  ['paste', 'Paste Rows', ClipboardPaste],
                ] as const
              ).map(([key, label, Icon]) => (
                <button
                  key={key}
                  type="button"
                  onClick={() => setInputMode(key)}
                  className={`inline-flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium rounded-md cursor-pointer transition-colors ${
                    inputMode === key
                      ? 'bg-white text-slate-900 shadow-sm dark:bg-slate-900 dark:text-white'
                      : 'text-slate-600 dark:text-slate-400'
                  }`}
                >
                  <Icon className="h-3.5 w-3.5" />
                  {label}
                </button>
              ))}
            </div>

            <Button type="button" variant="outline" size="sm" onClick={handleDownloadSampleCsv}>
              <Download className="h-3.5 w-3.5" />
              Sample CSV Template
            </Button>
          </div>

          {/* Batch Defaults */}
          <div className="grid grid-cols-1 sm:grid-cols-3 gap-3 rounded-xl border border-slate-200 dark:border-slate-800 p-3.5 bg-slate-50/60 dark:bg-slate-900/40">
            <Field label="Default Course (if blank in row)">
              <Select
                value={defaultCourseId}
                onChange={(e) => {
                  setDefaultCourseId(e.target.value);
                  setDefaultSemesterId('');
                }}
              >
                <option value="">Use row Department / Course</option>
                {courses.map((c) => (
                  <option key={c.id} value={c.id}>
                    {c.name} ({c.code})
                  </option>
                ))}
              </Select>
            </Field>
            <Field label="Default Semester">
              <Select value={defaultSemesterId} onChange={(e) => setDefaultSemesterId(e.target.value)}>
                <option value="">Optional</option>
                {filteredSemesters.map((s) => (
                  <option key={s.id} value={s.id}>
                    {s.name}
                  </option>
                ))}
              </Select>
            </Field>
            <Field label="Academic Session">
              <Select
                value={defaultAcademicSessionId}
                onChange={(e) => setDefaultAcademicSessionId(e.target.value)}
              >
                <option value="">Optional</option>
                {academicSessions.map((s) => (
                  <option key={s.id} value={s.id}>
                    {s.name}
                  </option>
                ))}
              </Select>
            </Field>
          </div>

          {inputMode === 'csv' && (
            <div className="rounded-xl border-2 border-dashed border-slate-300 dark:border-slate-700 p-8 text-center space-y-3">
              <Upload className="h-8 w-8 mx-auto text-[#2563EB]" />
              <div>
                <div className="text-sm font-semibold text-slate-900 dark:text-white">
                  Upload Student Roster CSV
                </div>
                <p className="text-xs text-slate-500 mt-1">
                  Supported columns: <span className="font-mono">Name, RollNo, DepartmentCourse, Email, Phone, Password</span> (Email, Phone &amp; Password are optional).
                </p>
              </div>
              <input
                ref={fileInputRef}
                type="file"
                accept=".csv,text/csv"
                onChange={handleCsvUpload}
                className="hidden"
              />
              <Button type="button" onClick={() => fileInputRef.current?.click()}>
                <Upload className="h-4 w-4" />
                Select CSV File
              </Button>
            </div>
          )}

          {inputMode === 'paste' && (
            <div className="space-y-3">
              <Field
                label="Paste Rows (from Excel, Google Sheets, or CSV)"
                hint="Columns order: Name, Roll No / Student ID, Department/Course, Email (optional), Phone (optional), Password (optional)"
              >
                <Textarea
                  rows={7}
                  value={pasteText}
                  onChange={(e) => setPasteText(e.target.value)}
                  placeholder={`Aarav Sharma, BCA-2026-101, BCA, aarav@college.edu, 9876543210,\nZoya Khan, BCA-2026-102, BCA, , 9876543211,`}
                  className="font-mono text-xs"
                />
              </Field>
              <div className="flex justify-end">
                <Button type="button" onClick={handleParsePasted}>
                  Load Pasted Rows into Table
                </Button>
              </div>
            </div>
          )}

          {inputMode === 'table' && (
            <div className="space-y-2.5">
              <div className="overflow-x-auto rounded-xl border border-slate-200 dark:border-slate-800 max-h-80">
                <table className="w-full text-left text-xs">
                  <thead className="sticky top-0 z-10 border-b border-slate-200 bg-slate-50 font-semibold text-slate-600 dark:border-slate-800 dark:bg-slate-900 dark:text-slate-300">
                    <tr>
                      <th className="px-2.5 py-2 w-8">#</th>
                      <th className="px-2.5 py-2 min-w-[155px]">Full Name *</th>
                      <th className="px-2.5 py-2 min-w-[130px]">Roll No / ID *</th>
                      <th className="px-2.5 py-2 min-w-[125px]">Dept / Course</th>
                      <th className="px-2.5 py-2 min-w-[165px]">Email (optional)</th>
                      <th className="px-2.5 py-2 min-w-[115px]">Phone (opt)</th>
                      <th className="px-2.5 py-2 min-w-[125px]">Password (auto)</th>
                      <th className="px-2 py-2 w-9" />
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-slate-100 dark:divide-slate-800">
                    {rows.map((row, idx) => {
                      const warn = rowWarnings.get(row.id);
                      return (
                        <tr
                          key={row.id}
                          className={warn ? 'bg-amber-50/70 dark:bg-amber-950/20' : undefined}
                        >
                          <td className="px-2.5 py-1.5 font-mono text-slate-400">{idx + 1}</td>
                          <td className="px-1.5 py-1.5">
                            <Input
                              value={row.fullName}
                              onChange={(e) => updateRow(row.id, 'fullName', e.target.value)}
                              placeholder="Student Name"
                              className="h-8 text-xs"
                            />
                            {warn && (
                              <div className="text-[10px] text-amber-700 dark:text-amber-400 mt-0.5 font-medium">
                                {warn}
                              </div>
                            )}
                          </td>
                          <td className="px-1.5 py-1.5">
                            <Input
                              value={row.collegeRollNumber}
                              onChange={(e) => updateRow(row.id, 'collegeRollNumber', e.target.value)}
                              placeholder="BCA-2026-101"
                              className="h-8 text-xs font-mono"
                            />
                          </td>
                          <td className="px-1.5 py-1.5">
                            <Input
                              value={row.departmentOrCourse}
                              onChange={(e) => updateRow(row.id, 'departmentOrCourse', e.target.value)}
                              placeholder="BCA / B.Sc"
                              className="h-8 text-xs"
                            />
                          </td>
                          <td className="px-1.5 py-1.5">
                            <Input
                              type="email"
                              value={row.email}
                              onChange={(e) => updateRow(row.id, 'email', e.target.value)}
                              placeholder="Auto-generated if blank"
                              className="h-8 text-xs"
                            />
                          </td>
                          <td className="px-1.5 py-1.5">
                            <Input
                              value={row.phone}
                              onChange={(e) => updateRow(row.id, 'phone', e.target.value)}
                              placeholder="Optional"
                              className="h-8 text-xs"
                            />
                          </td>
                          <td className="px-1.5 py-1.5">
                            <Input
                              value={row.password}
                              onChange={(e) => updateRow(row.id, 'password', e.target.value)}
                              placeholder="Auto strong"
                              className="h-8 text-xs font-mono"
                            />
                          </td>
                          <td className="px-1.5 py-1.5 text-center">
                            <button
                              type="button"
                              onClick={() => removeRow(row.id)}
                              className="p-1 text-slate-400 hover:text-red-500 cursor-pointer"
                              title="Remove row"
                            >
                              <Trash2 className="h-3.5 w-3.5" />
                            </button>
                          </td>
                        </tr>
                      );
                    })}
                  </tbody>
                </table>
              </div>

              <div className="flex flex-wrap items-center justify-between gap-2">
                <div className="flex items-center gap-2">
                  <Button
                    type="button"
                    size="sm"
                    variant="outline"
                    onClick={() => setRows((prev) => [...prev, makeEmptyRow()])}
                  >
                    <Plus className="h-3.5 w-3.5" />
                    Add Row
                  </Button>
                  <Button
                    type="button"
                    size="sm"
                    variant="ghost"
                    onClick={() =>
                      setRows((prev) => [...prev, makeEmptyRow(), makeEmptyRow(), makeEmptyRow(), makeEmptyRow(), makeEmptyRow()])
                    }
                  >
                    +5 Rows
                  </Button>
                </div>

                <label className="inline-flex items-center gap-2 text-xs text-slate-600 dark:text-slate-300 cursor-pointer">
                  <input
                    type="checkbox"
                    checked={autoGenerateId}
                    onChange={(e) => setAutoGenerateId(e.target.checked)}
                    className="h-3.5 w-3.5 rounded"
                  />
                  Auto-issue active Digital Library ID card for each student
                </label>
              </div>
            </div>
          )}

          {/* Footer Submit */}
          <div className="flex flex-wrap items-center justify-between gap-3 pt-3 border-t border-slate-200 dark:border-slate-800">
            <div className="text-xs text-slate-500">
              <strong className="text-slate-800 dark:text-slate-200">{nonEmptyRows.length}</strong> student row(s) ready
              {rowWarnings.size > 0 && (
                <span className="ml-2 text-amber-600 dark:text-amber-400 font-medium">
                  · {rowWarnings.size} row(s) have warnings (duplicates will be safely skipped)
                </span>
              )}
            </div>
            <div className="flex items-center gap-2">
              <Button type="button" variant="outline" onClick={() => onOpenChange(false)}>
                Cancel
              </Button>
              <Button
                type="button"
                loading={submitting}
                disabled={nonEmptyRows.length === 0}
                onClick={handleSubmitBulk}
              >
                <Users className="h-4 w-4" />
                Create {nonEmptyRows.length} Student Account{nonEmptyRows.length === 1 ? '' : 's'}
              </Button>
            </div>
          </div>
        </div>
      )}
    </Modal>
  );
}
